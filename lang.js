/* =========================
   ORIGINAL TEXT
========================= */

const originalTexts = new WeakMap();


function normalizeText(text) {
    return text
        .replace(/\s+/g, " ")
        .trim();
}



function translateI18nElements(lang) {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.dataset.i18n;
        const translated = translations[lang]?.[key];

        if (!translated) return;

        el.textContent = translated;
    });
}

/* =========================
   TRANSLATE TEXT NODE
========================= */

function translateTextNode(node, lang) {

    if (!originalTexts.has(node)) {
        originalTexts.set(node, node.nodeValue);
    }

    const original = originalTexts.get(node);
    const clean = normalizeText(original);

    if (!clean) return;

    if (lang === "uz") {
        node.nodeValue = original;
        return;
    }

    const translated = translations[lang]?.[clean];

    if (translated) {
        const leading = original.match(/^\s*/)?.[0] || "";
        const trailing = original.match(/\s*$/)?.[0] || "";

        node.nodeValue = leading + translated + trailing;
    }
}


/* =========================
   WALK THROUGH PAGE
========================= */

function translateElement(element, lang) {

    const walker = document.createTreeWalker(
        element,
        NodeFilter.SHOW_TEXT
    );

    const nodes = [];

    while (walker.nextNode()) {
        nodes.push(walker.currentNode);
    }

    nodes.forEach(node => {

        const parent = node.parentElement;

        if (!parent) return;

        if (
            parent.closest("script") ||
            parent.closest("style") ||
            parent.closest("noscript")
        ) {
            return;
        }

        translateTextNode(node, lang);
    });


    element.querySelectorAll("[placeholder]").forEach(input => {

    if (!input.dataset.originalPlaceholder) {
        input.dataset.originalPlaceholder = input.placeholder;
    }

    const original = input.dataset.originalPlaceholder;

    if (lang === "uz") {
        input.placeholder = original;
        return;
    }

    input.placeholder =
        translations[lang]?.[original] || original;
});
}


/* =========================
   LANGUAGE
========================= */

function setLanguage(lang) {

    if (!["uz", "ru", "zh"].includes(lang)) {
        lang = "uz";
    }

    translateElement(document.body, lang);
    translateI18nElements(lang);

    document.documentElement.lang =
        lang === "zh" ? "zh-CN" : lang;

    localStorage.setItem(BBA_LANG_KEY, lang);

    document
        .querySelectorAll(".mobile-lang-btn")
        .forEach(button => {
            button.classList.toggle(
                "active",
                button.dataset.lang === lang
            );
        });
}


/* =========================
   BUTTONS
========================= */

document.addEventListener("DOMContentLoaded", () => {

    const savedLanguage =
        localStorage.getItem(BBA_LANG_KEY) || "uz";

    setLanguage(savedLanguage);

    document
        .querySelectorAll(".mobile-lang-btn")
        .forEach(button => {

            button.addEventListener("click", () => {
                setLanguage(button.dataset.lang);
            });

        });

});